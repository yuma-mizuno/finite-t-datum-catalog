'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const root=__dirname,qa=path.join(root,'.qa');fs.mkdirSync(qa,{recursive:true});
const data=JSON.parse(fs.readFileSync(path.join(root,'catalogue.json'),'utf8'));
const url=pathToFileURL(path.join(root,'index.html')).href;
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:1050},offline:true,acceptDownloads:true});
    const page=await context.newPage(),errors=[],requests=[];
    page.on('pageerror',e=>errors.push(String(e)));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
    const route=async(id,tab='matrices')=>{await page.goto(url+'#'+id+'/'+tab);await page.waitForFunction(([id,tab])=>document.querySelector('#record-header .eyebrow').textContent.endsWith(id)&&document.querySelector('#tab-'+tab).getAttribute('aria-selected')==='true',[id,tab]);};
    await route('r4-c01');
    assert.equal(await page.locator('.record-link').count(),data.records.filter(r=>r.rank===4).length);
    await page.screenshot({path:path.join(qa,'rank4-matrices.png'),fullPage:true});
    await page.locator('#navigator-filters summary').click();
    await page.selectOption('#form','degree2');assert.equal(await page.locator('.record-link').count(),data.records.filter(r=>r.rank===4&&r.datum.delays.every(x=>x===2)).length);
    await page.click('[data-rank="3"]');await page.waitForFunction(()=>document.querySelector('#record-header .eyebrow').textContent.endsWith('r3-c01'));
    assert.equal(await page.locator('.record-link').count(),data.records.filter(r=>r.rank===3).length);
    await page.click('[data-rank="all"]');assert.equal(await page.locator('.record-link').count(),data.records.length);
    for(const [rank,count] of [[1,2],[2,6],[5,55],[6,108]]){
      await page.click(`[data-rank="${rank}"]`);
      await page.waitForFunction(rank=>document.querySelector('#record-header .eyebrow').textContent.startsWith('Rank '+rank),rank);
      assert.equal(await page.locator('.record-link').count(),data.records.filter(r=>r.rank===rank).length);
    }
    await page.click('[data-rank="all"]');
    await page.selectOption('#symmetrizer-filter','identity');assert.equal(await page.locator('.record-link').count(),224);
    await page.selectOption('#symmetrizer-filter','positive_diagonal');assert.equal(await page.locator('.record-link').count(),data.records.length-224);
    await page.selectOption('#symmetrizer-filter','all');
    for(const family of ['RSG','SG','Zamolodchikov','Commuting Cartan','Fold','Literature example']){
      await page.selectOption('#family-filter',family);
      assert.equal(await page.locator('.record-link').count(),data.records.filter(r=>r.notes.family.identifications.some(x=>x.category===family)).length);
    }
    await page.selectOption('#family-filter','all');
    await page.selectOption('#quiver-filter','certified-surface');assert.equal(await page.locator('.record-link').count(),data.records.filter(r=>r.notes.quiver.status==='certified-surface').length);
    await page.selectOption('#quiver-filter','all');
    await page.fill('#search','r4-c19');assert.equal(await page.locator('.record-link').count(),1);
    await page.click('[data-record="r4-c19"]');await page.waitForFunction(()=>document.title.includes('Class 19'));
    await page.fill('#search','no such record');assert.equal(await page.locator('.record-link').count(),0);
    await page.fill('#search','');await page.selectOption('#sort','period');
    const first=await page.locator('.record-link').first().getAttribute('data-record');
    assert.equal(data.records.find(r=>r.id===first).periodicity.labelled_period,Math.min(...data.records.map(r=>r.periodicity.labelled_period)));
    for(const r of data.records){
      await route(r.id);
      assert.equal(await page.locator('#record-header h2').textContent(),'Class '+r.class_number);
      assert.equal(await page.title(),'Rank '+r.rank+' · Class '+r.class_number+' | Finite T-data');
      const actual=await page.locator('#panel-matrices .matrix-section:not(.ratio-section) table').evaluateAll(tables=>tables.map(t=>[...t.rows].map(row=>[...row.cells].map(cell=>Number(cell.textContent.replace(/−/g,'-'))))));
      assert.deepEqual(actual,[r.datum.A_plus_1,r.datum.A_minus_1],r.id+' rendered constants');
      assert.equal(await page.locator('#panel-matrices table').count(),6);
      const ratios=await page.locator('.ratio-section table').evaluateAll(tables=>tables.map(t=>[...t.rows].map(row=>[...row.cells].map(cell=>cell.querySelector('.fraction')?[...cell.querySelector('.fraction').children].map(x=>x.textContent).join('/'):cell.textContent.replace(/−/g,'-')))));
      assert.deepEqual(ratios,[r.matrix_ratios.A_plus_inverse_A_minus,r.matrix_ratios.A_minus_inverse_A_plus],r.id+' rendered rational ratios');
      await page.click('#tab-exponents');
      const multiplicities=await page.locator('.spectrum-table tbody tr').evaluateAll(rows=>rows.map(row=>({m:Number(row.cells[0].textContent),multiplicity:Number(row.cells[1].textContent)})));
      assert.deepEqual(multiplicities,r.exponents.multiplicities,r.id+' rendered spectrum');
      assert.equal(await page.locator('#spectrum [data-root]').count(),multiplicities.length);
    }
    await page.click('[data-rank="6"]');
    await route('r6-c108');
    await page.selectOption('#sort','class');
    const labels=await page.locator('.record-link strong').allTextContents();
    assert.deepEqual(labels,Array.from({length:188},(_,i)=>'Class '+(i+1)));
    await page.click('#next-record');
    await page.waitForFunction(()=>document.querySelector('#record-header .eyebrow').textContent.endsWith('r6-c109'));
    await page.fill('#search','r6-c109');assert.equal(await page.locator('.record-link').count(),1);
    await page.fill('#search','');
    await page.click('#previous-record');
    await page.waitForFunction(()=>document.querySelector('#record-header .eyebrow').textContent.endsWith('r6-c108'));
    await route('r2-c02','notes');await page.locator('details.family-note').first().locator('summary').click();
    assert.match(await page.locator('#panel-notes').textContent(),/RSG\(3, 1\)/);
    assert.match(await page.locator('#panel-notes').textContent(),/generation order/);
    await page.screenshot({path:path.join(qa,'rank2-family-notes.png'),fullPage:true});
    for(const id of ['r1-c01','r2-c03','r3-c06','r4-c32','r4-c19','r5-c16','r5-c31','r5-c54']){
      await route(id,'notes');await page.click('#replay-class');
      await page.waitForFunction(()=>document.querySelector('#tab-mutation').getAttribute('aria-selected')==='true');
      assert.equal(await page.locator('#mutation-mode').inputValue(),'certificate');
      assert(await page.locator('#terminal-relabel').isHidden());
      await page.evaluate(()=>{let limit=500;while(!document.querySelector('#loop-next').disabled&&limit--)document.querySelector('#loop-next').click();if(limit<=0)throw Error('Certificate failed to finish');});
      assert.match(await page.locator('#step-label').textContent(),/Certificate target reached/);
      const target=await page.locator('#exchange-matrix table').evaluate(t=>[...t.rows].map(row=>[...row.cells].map(cell=>Number(cell.textContent.replace(/−/g,'-')))));
      assert.deepEqual(target,data.records.find(r=>r.id===id).notes.quiver.certificate.target_B);
      if(id==='r4-c32')await page.screenshot({path:path.join(qa,'surface-certificate.png'),fullPage:true});
      await page.selectOption('#mutation-mode','loop');assert.match(await page.locator('#step-label').textContent(),/Initial slice/);
    }
    await route('r4-c01','exponents');
    const repeated=data.records.find(r=>r.id==='r4-c01').exponents.multiplicities.find(x=>x.multiplicity>1);
    assert(repeated);await page.locator(`[data-root="${repeated.m}"]`).click();
    assert.match(await page.locator('#spectrum-selection').textContent(),new RegExp('multiplicity '+repeated.multiplicity));
    await page.screenshot({path:path.join(qa,'exponents-multiplicities.png'),fullPage:true});
    await page.locator('#panel-exponents details').last().locator('summary').click();
    const spectrumDownload=page.waitForEvent('download');await page.click('#export-spectrum-certificate');const spectrum=await spectrumDownload;await spectrum.saveAs(path.join(qa,'spectrum.json'));
    const spectrumData=JSON.parse(fs.readFileSync(path.join(qa,'spectrum.json'),'utf8'));
    assert.deepEqual(spectrumData.values,data.records.find(r=>r.id==='r4-c01').exponents.values);
    await route('r1-c01','family');assert.equal(await page.locator('[id^="shift-"]').count(),0);
    await page.fill('#scale','3');assert.match(await page.locator('#family-result').textContent(),/Admissible polynomial lift/);
    await route('r4-c19');await page.screenshot({path:path.join(qa,'rank4-class19.png'),fullPage:true});
    await page.click('[data-kind="N"]');assert.equal(await page.locator('[data-kind="N"]').getAttribute('aria-pressed'),'true');
    await route('r4-c01','family');
    await page.fill('#scale','3/2');
    for(let i=0;i<3;i++)await page.fill('#shift-'+i,'1/2');
    assert.equal(await page.locator('#family-result .validity strong').textContent(),'Admissible polynomial lift');
    assert.equal(await page.locator('#export-lift').isEnabled(),true);
    assert.match(await page.locator('.transformed-delays').textContent(),/3, 3, 3, 3/);
    await page.screenshot({path:path.join(qa,'admissible-lift.png'),fullPage:true});
    const liftDownload=page.waitForEvent('download');await page.click('#export-lift');
    const lift=await liftDownload;await lift.saveAs(path.join(qa,'lift.json'));
    const liftData=JSON.parse(fs.readFileSync(path.join(qa,'lift.json'),'utf8'));
    assert.equal(liftData.parameters.lambda,'3/2');assert.deepEqual(liftData.datum.N_minus[0][3],[['1','2']]);
    assert.deepEqual(liftData.matrix_ratios,data.records.find(r=>r.id==='r4-c01').matrix_ratios);
    await page.fill('#scale','0');assert.equal(await page.locator('#export-lift').isDisabled(),true);
    assert.match(await page.locator('#family-result').textContent(),/must be positive/);
    await page.fill('#scale','1/0');assert.match(await page.locator('#family-result').textContent(),/denominator/);
    await page.click('#family-reset');assert.equal(await page.locator('#scale').inputValue(),'1');
    await page.fill('#scale','9007199254740993');assert.match(await page.locator('.transformed-delays').textContent(),/18014398509481986/);
    await route('r4-c19','mutation');
    const word=data.records.find(r=>r.id==='r4-c19').slice.mutation_word;
    await page.locator('[data-vertex="0"]').click();assert.match(await page.locator('#graph-caption').textContent(),/Vertex 1, weight 1:/);
    await page.click('#loop-next');await page.screenshot({path:path.join(qa,'mutation-loop.png'),fullPage:true});
    for(let i=0;i<word.length;i++)await page.click('#loop-next');
    assert.match(await page.locator('#step-label').textContent(),/Loop closed/);assert(await page.locator('#loop-next').isDisabled());
    await page.click('#loop-prev');assert(await page.locator('#loop-next').isEnabled());
    await page.click('#loop-reset');assert.match(await page.locator('#step-label').textContent(),/Initial slice/);
    await page.click('#tab-evidence');await page.locator('#panel-evidence details').first().locator('summary').click();
    assert.match(await page.locator('#panel-evidence').textContent(),/UNSAT/);
    await page.click('#tab-proof');await page.locator('.proof-step').nth(1).locator('summary').click();
    await page.screenshot({path:path.join(qa,'classification.png'),fullPage:true});
    await page.focus('#tab-proof');await page.keyboard.press('ArrowLeft');await page.waitForFunction(()=>document.querySelector('#tab-evidence').getAttribute('aria-selected')==='true');
    const baseDownload=page.waitForEvent('download');await page.click('#export-record');const base=await baseDownload;await base.saveAs(path.join(qa,'record.json'));
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(qa,'record.json'),'utf8')),data.records.find(r=>r.id==='r4-c19'));
    const texDownload=page.waitForEvent('download');await page.click('#export-tex');const tex=await texDownload;await tex.saveAs(path.join(qa,'record.tex'));
    assert.match(fs.readFileSync(path.join(qa,'record.tex'),'utf8'),/A_\{\+\}\(1\)/);
    await page.setViewportSize({width:390,height:844});await route('r4-c19');
    await page.screenshot({path:path.join(qa,'mobile-matrices.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page should not overflow horizontally.');
    await route('r4-c19','mutation');await page.locator('#panel-mutation').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(qa,'mobile-mutation.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.reload();await page.waitForFunction(()=>document.querySelector('#tab-mutation').getAttribute('aria-selected')==='true');
    assert.equal(await page.locator('#record-header .eyebrow').textContent(),'Rank 4 · r4-c19');
    await route('r4-c01','exponents');await page.locator('#panel-exponents').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(qa,'mobile-exponents.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    assert.deepEqual(errors,[],'No browser exceptions');assert.deepEqual(requests,[],'No HTTP requests from the document');
    console.log(`PASS: offline browser; all ${data.records.length} specializations, ratios and exponent tables; rank and symmetrizer filters, witness replay, exports, lifts, loops, keyboard tabs and mobile layout.`);
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
